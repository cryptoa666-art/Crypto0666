export function categoryOf(symbol: string, name = "", price?: number | null): CoinUse {
  const sym = symbol.toUpperCase();
  const mapped = USE_BY_SYMBOL[sym];
  if (mapped) return mapped;
  const hay = `${sym} ${name}`.toLowerCase();
  if (/(usd|tether|dollar|stable)/.test(hay) && (price == null || Math.abs(price - 1) < 0.05)) {
    return "stable";
  }
  if (/(pepe|doge|inu|meme|cat|neiro)/.test(hay)) return "meme";
  if (/(wrapped|staked|beacon)/.test(hay)) return "infra";
  return "other";
}
